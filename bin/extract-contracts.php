<?php
/**
 * API contracts: every GraphQL operation the plugin can send, taken straight
 * from the source with PHP's tokenizer (all queries are string literals passed
 * to request()). The hub validates these files against the live Vetspire and
 * Nectar schemas every 6 hours and alerts when one would stop working.
 *
 *   php bin/extract-contracts.php          rewrite contracts/*.graphql
 *   php bin/extract-contracts.php --check  exit 1 if they are out of date
 *
 * Input-object fields sent in variables are not visible here; tests record
 * those into contracts/*.inputs.json (see tests/contract-recorder.php).
 */

$root    = dirname( __DIR__ );
$sources = array(
	'vetspire' => $root . '/includes/class-vsps-api.php',
	'nectar'   => $root . '/includes/class-vsps-nectar.php',
);

require __DIR__ . '/contracts-lib.php';

$check = in_array( '--check', $argv, true );
$stale = array();
foreach ( $sources as $pims => $file ) {
	$ops    = vsps_operations_in( $file );
	$target = $root . '/contracts/' . $pims . '.graphql';
	$text   = '# ' . $pims . ' operations sent by the Vetcelerator Scheduler plugin.' . "\n"
		. '# Generated by bin/extract-contracts.php from ' . basename( $file ) . '; do not edit by hand.' . "\n\n"
		. implode( "\n\n", $ops ) . "\n";
	if ( $check ) {
		// Line endings don't matter (Windows checkouts may convert them).
		if ( ! is_file( $target ) || str_replace( "\r\n", "\n", file_get_contents( $target ) ) !== $text ) {
			$stale[] = 'contracts/' . $pims . '.graphql';
		}
		continue;
	}
	if ( ! is_dir( dirname( $target ) ) ) {
		mkdir( dirname( $target ), 0777, true );
	}
	file_put_contents( $target, $text );
	echo $pims . ': ' . count( $ops ) . " operations\n";
}

if ( $check ) {
	if ( $stale ) {
		fwrite( STDERR, 'Out of date: ' . implode( ', ', $stale ) . ". Run: php bin/extract-contracts.php\n" );
		exit( 1 );
	}
	echo "contracts up to date\n";
}
